#!/usr/bin/env bash
# Development stack for Nexora WorkStudio: disposable Postgres + Redis containers
# (loopback only), generated secrets in git-ignored env files, database migrations.
# Then run the app with:      cd workstudio/apps/sim && bun run dev -- --port 3100   (or scripts/dev/app.sh)
# and the realtime server:     cd workstudio/apps/realtime && bun run dev
# Docker access goes through `sg docker` when the shell is not yet in the docker group.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
WS="$ROOT/workstudio"
DB_PORT="${NEXORA_DEV_DB_PORT:-15432}"
REDIS_PORT="${NEXORA_DEV_REDIS_PORT:-16379}"
APP_PORT="${NEXORA_DEV_APP_PORT:-3100}"
RT_PORT="${NEXORA_DEV_REALTIME_PORT:-3102}"

docker_cmd() { if docker info >/dev/null 2>&1; then docker "$@"; else sg docker -c "docker $(printf '%q ' "$@")"; fi; }
rand() { openssl rand -hex "${1:-32}"; }

SECRETS="$ROOT/scripts/dev/.secrets"
if [ ! -f "$SECRETS" ]; then
  umask 077
  cat > "$SECRETS" <<SECRETS_EOF
POSTGRES_PASSWORD=$(rand 24)
BETTER_AUTH_SECRET=$(rand)
ENCRYPTION_KEY=$(rand)
INTERNAL_API_SECRET=$(rand)
API_ENCRYPTION_KEY=$(rand)
CRON_SECRET=$(rand)
SECRETS_EOF
fi
# shellcheck disable=SC1090
source "$SECRETS"

if ! docker_cmd ps -a --format '{{.Names}}' | grep -qx nexora-dev-db; then
  docker_cmd run -d --name nexora-dev-db --restart unless-stopped -p "127.0.0.1:${DB_PORT}:5432" \
    -e POSTGRES_USER=postgres -e "POSTGRES_PASSWORD=${POSTGRES_PASSWORD}" -e POSTGRES_DB=nexora \
    -v nexora-dev-db:/var/lib/postgresql/data pgvector/pgvector:pg17 >/dev/null
fi
if ! docker_cmd ps -a --format '{{.Names}}' | grep -qx nexora-dev-redis; then
  docker_cmd run -d --name nexora-dev-redis --restart unless-stopped -p "127.0.0.1:${REDIS_PORT}:6379" redis:7-alpine >/dev/null
fi
docker_cmd start nexora-dev-db nexora-dev-redis >/dev/null

DATABASE_URL="postgresql://postgres:${POSTGRES_PASSWORD}@127.0.0.1:${DB_PORT}/nexora"
umask 077
cat > "$WS/apps/sim/.env.local" <<ENV_EOF
# Generated by scripts/dev/up.sh — development only, never commit.
DATABASE_URL=${DATABASE_URL}
REDIS_URL=redis://127.0.0.1:${REDIS_PORT}
BETTER_AUTH_SECRET=${BETTER_AUTH_SECRET}
BETTER_AUTH_URL=http://localhost:${APP_PORT}
NEXT_PUBLIC_APP_URL=http://localhost:${APP_PORT}
ENCRYPTION_KEY=${ENCRYPTION_KEY}
INTERNAL_API_SECRET=${INTERNAL_API_SECRET}
API_ENCRYPTION_KEY=${API_ENCRYPTION_KEY}
CRON_SECRET=${CRON_SECRET}
SOCKET_SERVER_URL=http://localhost:${RT_PORT}
NEXT_PUBLIC_SOCKET_URL=http://localhost:${RT_PORT}
NEXT_TELEMETRY_DISABLED=1
${NEXORA_DEV_EXTRA_ENV:-}
ENV_EOF
cat > "$WS/apps/realtime/.env" <<ENV_EOF
# Generated by scripts/dev/up.sh — development only, never commit.
NODE_ENV=development
PORT=${RT_PORT}
HOST=127.0.0.1
DATABASE_URL=${DATABASE_URL}
REDIS_URL=redis://127.0.0.1:${REDIS_PORT}
BETTER_AUTH_URL=http://localhost:${APP_PORT}
BETTER_AUTH_SECRET=${BETTER_AUTH_SECRET}
INTERNAL_API_SECRET=${INTERNAL_API_SECRET}
NEXT_PUBLIC_APP_URL=http://localhost:${APP_PORT}
ENV_EOF
printf 'DATABASE_URL=%s\n' "$DATABASE_URL" > "$WS/packages/db/.env"

for _ in $(seq 1 30); do docker_cmd exec nexora-dev-db pg_isready -U postgres >/dev/null 2>&1 && break; sleep 1; done
(cd "$WS/packages/db" && bun run db:migrate)
echo "nexora dev stack ready: db 127.0.0.1:${DB_PORT}, redis 127.0.0.1:${REDIS_PORT}, app port ${APP_PORT}, realtime port ${RT_PORT}"
